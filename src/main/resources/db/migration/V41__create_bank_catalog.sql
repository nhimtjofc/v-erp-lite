    id UUID PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    bin VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (code),
    UNIQUE (name),
    UNIQUE (bin)
);

